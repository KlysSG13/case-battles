import { PrismaClient } from "@prisma/client";
import { evaluateAnswer } from "../lib/evaluator";

const prisma = new PrismaClient();

const STRONG = `Решение строю на цифрах и приоритетах.
1. Фиксирую экономику точки: маржа после переменных затрат ~60 тыс./мес., запас прочности низкий, поэтому кредит под 24% — не первый инструмент.
2. Первые 2 недели защищаю ядро: утренний пик 7:30–10:00 даёт 60% продаж — добавляю предзаказ через мини-приложение и вторую смену с 7:00, цель +8 чашек в день (~+62 тыс. выручки/мес.).
3. Сотрудник: повышаю до 70 тыс. с KPI за скорость и средний чек — замена и обучение новичка обойдутся дороже (подбор 30 тыс. + 2 недели падения выручки).
4. Конкурент: не воюю ценой, усиливаю программу лояльности (6-й кофе в подарок), себестоимость акции ~4% выручки.
5. Вторая точка и большое помещение — только после 2 месяцев стабильной маржи 8–10%: считаю точку безубыточности БЦ-точки (130 тыс. аренда + 100 тыс. ФОТ), при потоке 250 чел. и конверсии 12% выручка ~234 тыс. — на грани, откладываю.
Риски: перегрев аренды, демпинг сети — покрываю удержанием постоянных клиентов, а не скидками всем. Метрики контроля: выручка/день, средний чек, доля постоянных клиентов — раз в неделю.`;

const MEDIUM = `Сначала разберусь с конкурентом: у него цены ниже, но очередь и нет вкуса. Я бы улучшил качество зерна и добавил пару новых позиций, чтобы отличаться.
Сотрудника повышу до 70 тысяч, он хороший, терять дорого — это дешевле, чем искать нового.
Большое помещение брать рано: ремонт 1,2 млн и аренда 150 тыс. съедят всю прибыль. Сначала подниму выручку на текущей точке, месяц-два посмотрю цифры.
Кредит под 24% брать не хочу, дорого. Если что — есть семейный резерв 900 тысяч.
По второй точке в бизнес-центре надо съездить ещё раз и посчитать трафик в течение недели. Если поток реально 250 человек, можно попробовать, но сначала мелкий формат — островок, а не полное кафе.
Главное — не наращивать расходы, пока не понял, что случится с потоком после открытия сети.`;

const WEAK = `Мне кажется, надо просто подождать, пока всё само наладится. Конкуренты приходят и уходят, наш клиент всё равно к нам ходит, привык.
Сотрудника пусть не обижается, никому не повышаем, потом посмотрим. Если уйдёт — найдём нового, без проблем, бариста сейчас много.
Помещение побольше красивое, но дорого. А кредит банк уже одобрил, так что можно взять и сделать красиво, там будет посадка и кухня.
Вторую точку я бы открыл, чем быстрее тем лучше, там поток хороший вроде бы.
В общем, действуем по обстановке.`;

async function main(): Promise<void> {
  const found = await prisma.case.findFirst({
    where: { isActive: true },
    include: { criteria: true, domain: true },
    orderBy: { id: "asc" },
  });
  if (!found) {
    console.error("В базе нет кейсов — сначала выполните: npm run db:seed");
    process.exit(1);
  }
  console.log(`Кейс: «${found.title}» (${found.domain.title}), критериев: ${found.criteria.length}\n`);

  const tests: { label: string; answer: string }[] = [
    { label: "СИЛЬНЫЙ", answer: STRONG },
    { label: "СРЕДНИЙ", answer: MEDIUM },
    { label: "СЛАБЫЙ", answer: WEAK },
  ];

  for (const t of tests) {
    const outcome = await evaluateAnswer({
      caseTitle: found.title,
      caseBody: found.body,
      criteria: found.criteria.map((c) => ({
        name: c.name,
        description: c.description,
        weight: c.weight,
        maxPoints: c.maxPoints,
      })),
      answer: t.answer,
      timeSpentSec: 180,
    });
    console.log(`— ${t.label} ответ (${t.answer.length} симв.) —`);
    if (!outcome.ok) {
      console.log(`  ✗ ОЦЕНКА НЕ УДАЛАСЬ: ${outcome.error} (попыток: ${outcome.attemptsUsed})\n`);
      continue;
    }
    console.log(`  Движок: ${outcome.engine}, процент: ${outcome.percent}, попыток: ${outcome.attemptsUsed}, время: ${outcome.durationMs} мс`);
    for (const c of outcome.evaluation.criteria) {
      console.log(`  • ${c.name}: ${c.points}/10 — ${c.comment}`);
    }
    console.log(`  Сильные стороны: ${outcome.evaluation.strengths.join(" | ")}`);
    console.log(`  Зоны роста: ${outcome.evaluation.improvements.join(" | ")}\n`);
  }
}

main()
  .catch((e) => {
    console.error("Selfcheck failed:", e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
